def _get_risk_tolerance(preset: str) -> str:
    """Get risk tolerance description."""
    tolerances = {
        "Conservative": "Low - Preserves capital",
        "Moderate": "Medium - Balanced approach",
        "Aggressive": "High - Maximum returns",
    }
    return tolerances.get(preset, "Unknown")


def _get_stop_loss(preset: str) -> float:
    """Get stop loss percentage."""
    losses = {
        "Conservative": 2.0,
        "Moderate": 3.0,
        "Aggressive": 5.0,
    }
    return losses.get(preset, 2.0)


def _get_take_profit(preset: str) -> float:
    """Get take profit percentage."""
    profits = {
        "Conservative": 5.0,
        "Moderate": 7.0,
        "Aggressive": 10.0,
    }
    return profits.get(preset, 5.0)


def _assess_trade_count(trades: int) -> str:
    """Assess trade count."""
    if trades >= 50:
        return "✅ Sufficient"
    elif trades >= 20:
        return "⚠️ Moderate"
    else:
        return "❌ Insufficient"


def _assess_win_rate(win_rate: float) -> str:
    """Assess win rate."""
    if win_rate >= 60:
        return "✅ Excellent"
    elif win_rate >= 50:
        return "✅ Good"
    elif win_rate >= 40:
        return "⚠️ Acceptable"
    else:
        return "❌ Poor"


def _assess_return(ret: float) -> str:
    """Assess return."""
    if ret >= 20:
        return "✅ Strong"
    elif ret >= 10:
        return "✅ Good"
    elif ret >= 0:
        return "⚠️ Marginal"
    else:
        return "❌ Negative"


def _calculate_sharpe_estimate(ret: float, days: int) -> float:
    """Estimate Sharpe ratio."""
    if days <= 0 or ret <= 0:
        return 0.0
    annual_return = (ret / days) * 365
    # Simple estimate assuming 20% volatility
    estimated_vol = 20.0
    if estimated_vol == 0:
        return 0.0
    return (annual_return - 2.0) / estimated_vol


def _estimate_max_drawdown(ret: float) -> float:
    """Estimate max drawdown."""
    return abs(ret * 0.3)  # Estimate 30% of return as drawdown


def _calculate_sortino_estimate(ret: float, win_rate: float) -> float:
    """Estimate Sortino ratio (downside risk only)."""
    if ret <= 0 or win_rate < 50:
        return 0.0
    annual_return = ret / 2 * 365  # Simple estimate
    downside_vol = 15.0  # Estimate downside volatility
    return (annual_return - 2.0) / downside_vol


def _calculate_calmar_estimate(ret: float, drawdown: float) -> float:
    """Estimate Calmar ratio (return / max drawdown)."""
    if drawdown <= 0 or ret <= 0:
        return 0.0
    annual_return = ret / 2 * 365
    return annual_return / abs(drawdown) if drawdown != 0 else 0.0


def _calculate_cvar(metrics: Dict) -> float:
    """Calculate Conditional Value at Risk (CVaR / Expected Shortfall)."""
    max_dd = metrics.get("avg_total_return", 0) * 0.3  # Estimate from max drawdown
    # CVaR is typically worse than VaR
    return abs(max_dd * 1.3)


def _calculate_alpha_beta(avg_return: float, market_return: float = 10.0) -> Dict[str, float]:
    """Calculate alpha and beta vs benchmark (SPY)."""
    # Simple estimates
    alpha = avg_return - market_return  # Excess return
    beta = 0.8 if avg_return < market_return else 1.2  # Correlation estimate
    return {"alpha": alpha, "beta": beta}


def _monte_carlo_robustness_score(total_trades: int, win_rate: float) -> str:
    """Estimate Monte Carlo robustness score."""
    if total_trades < 20:
        return "Low (insufficient trades)"
    elif win_rate > 60:
        return "High (strong consistency)"
    elif win_rate > 45:
        return "Medium (acceptable consistency)"
    else:
        return "Low (needs optimization)"


def _estimate_recovery_time(ret: float) -> int:
    """Estimate recovery time."""
    if ret <= 0:
        return 999
    dd = _estimate_max_drawdown(ret)
    if dd == 0:
        return 30
    # Estimate 30-60 days recovery per 1% drawdown
    return int(dd * 45)


def _estimate_risk_reward(win_rate: float) -> float:
    """Estimate risk/reward ratio."""
    # If win rate is 50%, R/R should be 1:1 to break even
    if win_rate >= 50:
        return (win_rate - 50) / 50 + 1.0
    else:
        return win_rate / 50


def _generate_multi_strategy_section(multi_strategy_results: Optional[Dict]) -> str:
    """Generate multi-strategy analysis section."""
    if not multi_strategy_results:
        return ""

    per_strategy = multi_strategy_results.get("per_strategy", {})
    combined = multi_strategy_results.get("combined", {})
    allocation = multi_strategy_results.get("allocation", {})

    section = "\n## Multi-Strategy Portfolio Analysis\n\n"
    section += "### Capital Allocation\n\n"
    section += "| Strategy | Capital | Weight | Initial | Final | Trades | Win Rate | Return |\n"
    section += "|----------|---------|--------|---------|-------|--------|----------|--------|\n"

    total_initial = combined.get("total_initial_capital", 0)
    total_final = combined.get("total_final_capital", 0)

    for name in ["momentum", "mean_reversion", "pairs_trading"]:
        alloc_data = allocation.get(name, {})
        strat_data = per_strategy.get(name, {})

        capital = alloc_data.get("capital", 0)
        weight = alloc_data.get("weight", 0) * 100
        initial = strat_data.get("initial_capital", 0)
        final = strat_data.get("final_capital", 0)
        trades = strat_data.get("total_trades", 0)
        win_rate = strat_data.get("win_rate", 0)
        ret = strat_data.get("total_return", 0)

        section += f"| {name} | ${capital:,.0f} | {weight:.1f}% | ${initial:,.0f} | ${final:,.0f} | {trades} | {win_rate:.1f}% | {ret:.2f}% |\n"

    section += f"| **Total** | **${total_initial:,.0f}** | **100%** | **${total_initial:,.0f}** | **${total_final:,.0f}** | **{combined.get('total_trades', 0)}** | **{0:.1f}%** | **{combined.get('total_return', 0):.2f}%** |\n"

    section += "\n### Combined Performance\n\n"
    section += f"- **Total Return**: {combined.get('total_return', 0):.2f}%\n"
    section += f"- **Weighted Sharpe**: {combined.get('weighted_sharpe', 0):.3f}\n"
    section += f"- **Weighted Max DD**: {combined.get('weighted_max_dd', 0):.2f}%\n"

    return section


