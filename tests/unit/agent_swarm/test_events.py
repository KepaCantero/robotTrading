"""Unit tests for AgentEvent and AgentEventBus."""

import asyncio

from app.services.agent_swarm.events import (
    STAGE_COMPLETED,
    STAGE_STARTED,
    AgentEvent,
    AgentEventBus,
)


class TestAgentEvent:
    def test_to_dict_roundtrip(self):
        event = AgentEvent(STAGE_STARTED, "run_1", agent_id="t11", payload={"input": {}})
        data = event.to_dict()

        assert data["type"] == STAGE_STARTED
        assert data["run_id"] == "run_1"
        assert data["agent_id"] == "t11"

        restored = AgentEvent.from_dict(data)
        assert restored.type == event.type
        assert restored.run_id == event.run_id
        assert restored.agent_id == event.agent_id
        assert restored.payload == event.payload

    def test_timestamp_autogenerated(self):
        event = AgentEvent(STAGE_COMPLETED, "run_1")
        assert isinstance(event.timestamp, str)
        assert len(event.timestamp) > 10


class TestAgentEventBus:
    def test_publish_delivers_to_subscriber(self):
        bus = AgentEventBus()
        queue = bus.subscribe()

        bus.publish(AgentEvent(STAGE_STARTED, "run_1", agent_id="t11"))

        received = queue.get_nowait()
        assert received.type == STAGE_STARTED
        assert received.agent_id == "t11"

    def test_unsubscribe_stops_delivery(self):
        bus = AgentEventBus()
        queue = bus.subscribe()
        bus.unsubscribe(queue)

        bus.publish(AgentEvent(STAGE_STARTED, "run_1"))

        assert queue.empty()
        assert bus.subscriber_count == 0

    def test_publish_to_multiple_subscribers(self):
        bus = AgentEventBus()
        q1 = bus.subscribe()
        q2 = bus.subscribe()

        bus.publish(AgentEvent(STAGE_COMPLETED, "run_1", agent_id="t21"))

        assert q1.get_nowait().agent_id == "t21"
        assert q2.get_nowait().agent_id == "t21"

    def test_full_queue_drops_oldest_not_block(self):
        bus = AgentEventBus(queue_size=2)
        queue = bus.subscribe()

        for i in range(5):
            bus.publish(AgentEvent(STAGE_STARTED, "run_1", payload={"i": i}))

        first = queue.get_nowait()
        assert first.payload["i"] == 3  # oldest two were dropped
        assert queue.get_nowait().payload["i"] == 4

    def test_recent_events_history(self):
        bus = AgentEventBus(history_size=3)
        for i in range(5):
            bus.publish(AgentEvent(STAGE_STARTED, "run_1", payload={"i": i}))

        recent = bus.recent_events
        assert len(recent) == 3
        assert recent[-1].payload["i"] == 4

    def test_publish_from_inside_loop_is_non_blocking(self):
        async def scenario():
            bus = AgentEventBus()
            queue = bus.subscribe()
            bus.publish(AgentEvent(STAGE_STARTED, "run_1"))
            await asyncio.sleep(0)
            return queue.get_nowait()

        event = asyncio.run(scenario())
        assert event.type == STAGE_STARTED
